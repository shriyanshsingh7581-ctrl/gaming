/**
 * Pure helper to calculate Back or Lay liability and potential profit
 */
export function calculateExchangeBetMath(params: {
  betType: "BACK" | "LAY" | "YES" | "NO" | "GAME_BET";
  odds: number;
  stake: number;
}): { liability: number; potentialProfit: number; totalReturn: number } {
  const stake = Math.max(0, Math.round(params.stake));
  const odds = Math.max(1.01, Number(params.odds) || 1.9);

  if (params.betType === "LAY") {
    const liability = Math.max(1, Math.round(stake * (odds - 1)));
    const potentialProfit = stake;
    return {
      liability,
      potentialProfit,
      totalReturn: liability + potentialProfit,
    };
  }

  if (params.betType === "YES" || params.betType === "NO") {
    const rate = odds > 10 ? odds / 100 : odds - 1;
    const potentialProfit = Math.max(1, Math.round(stake * rate));
    return {
      liability: stake,
      potentialProfit,
      totalReturn: stake + potentialProfit,
    };
  }

  const potentialProfit = Math.max(1, Math.round(stake * (odds - 1)));
  return {
    liability: stake,
    potentialProfit,
    totalReturn: stake + potentialProfit,
  };
}

/**
 * Gently ticks live sports match odds in real time so Back/Lay prices breathe dynamically
 */
export function tickLiveSportsMatches(matches: LiveSportsMatch[]): LiveSportsMatch[] {
  return matches.map((m) => {
    if (m.suspended || !m.isLive) return m;
    const jitter = () => (Math.random() > 0.5 ? 0.01 : -0.01);
    const clampOdd = (val: number) =>
      Number(Math.min(25, Math.max(1.08, val + jitter())).toFixed(2));

    const nextHomeBack = clampOdd(m.runners.home.back);
    const nextHomeLay = Number((nextHomeBack + 0.02).toFixed(2));
    const nextAwayBack = clampOdd(m.runners.away.back);
    const nextAwayLay = Number((nextAwayBack + 0.03).toFixed(2));

    return {
      ...m,
      runners: {
        ...m.runners,
        home: { ...m.runners.home, back: nextHomeBack, lay: nextHomeLay },
        away: { ...m.runners.away, back: nextAwayBack, lay: nextAwayLay },
      },
    };
  });
}
