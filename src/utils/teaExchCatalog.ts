/**
 * Exact CDN image optimizer used on teaexch999.com/home (J(url, width, { quality: 75 }))
 */
export function formatTeaExchCdnImage(url: string, width = 336, quality = 75): string {
  if (!url) return "";
  try {
    const parsed = new URL(url);
    if (/^(prod|stage)-cdn\./.test(parsed.hostname) && !/\.(svg|gif)$/i.test(parsed.pathname)) {
      parsed.searchParams.set("width", String(width));
      parsed.searchParams.set("format", "webp");
      parsed.searchParams.set("quality", String(quality));
      return parsed.toString();
    }
    return url;
  } catch {
    return url;
  }
}

